def _json_code(value: object) -> str:
    """A JSON value as a code span: strings bare, everything else JSON-encoded."""
    return _code(value if isinstance(value, str) else json.dumps(value))


def _oneof_variant_name(variant: Mapping[str, object], index: int) -> str:
    """Name a discriminated-union variant: its discriminator's const, else its title."""
    for prop_schema in typing.cast(
        Mapping[str, Mapping[str, object]], variant.get("properties", {})
    ).values():
        if "const" in prop_schema:
            return str(prop_schema["const"])
    title = variant.get("title")
    return str(title) if title else f"variant {index + 1}"


def _oneof_variants(schema: Mapping[str, object]) -> list[Mapping[str, object]] | None:
    """The ``oneOf`` variants on this schema, under its nullable wrapper, or on its items.

    Mirrors the unwrapping in ``_schema_type`` so an optional discriminated
    union gets the same variants block as a required one. An ``anyOf`` with
    more than one non-null option is a real alternation, not a wrapper, and
    yields no block.
    """
    if "oneOf" in schema:
        return typing.cast(list[Mapping[str, object]], schema["oneOf"])
    if "anyOf" in schema:
        options = [
            option
            for option in typing.cast(list[Mapping[str, object]], schema["anyOf"])
            if option.get("type") != "null"
        ]
        return _oneof_variants(options[0]) if len(options) == 1 else None
    if schema.get("type") == "array":
        return _oneof_variants(
            typing.cast(Mapping[str, object], schema.get("items", {}))
        )
    return None


def _schema_type(schema: Mapping[str, object]) -> str:
    if "const" in schema:
        return _json_code(schema["const"])
    if "enum" in schema:
        values = typing.cast(list[object], schema["enum"])
        return "one of " + ", ".join(_json_code(value) for value in values)
    if "oneOf" in schema:
        options = typing.cast(list[Mapping[str, object]], schema["oneOf"])
        names = [
            _oneof_variant_name(option, index) for index, option in enumerate(options)
        ]
        return "one of " + ", ".join(_code(name) for name in names)
    if "anyOf" in schema:
        options = typing.cast(list[Mapping[str, object]], schema["anyOf"])
        parts = [
            _schema_type(option) for option in options if option.get("type") != "null"
        ]
        return " or ".join(dict.fromkeys(parts)) or "any"
    kind = schema.get("type")
    if kind == "array":
        items = typing.cast(Mapping[str, object], schema.get("items", {}))
        return f"array of {_schema_type(items)}"
    if kind == "object":
        extra = schema.get("additionalProperties")
        if isinstance(extra, Mapping):
            return f"object of {_schema_type(typing.cast(Mapping[str, object], extra))}"
        return "object"
    if isinstance(kind, list):
        return " or ".join(str(part) for part in kind if part != "null")
    return str(kind) if kind else "any"


_CONSTRAINT_KEYS = (
    ("minimum", "≥ {}"),
    ("exclusiveMinimum", "> {}"),
    ("maximum", "≤ {}"),
    ("exclusiveMaximum", "< {}"),
    ("minLength", "min length {}"),
    ("maxLength", "max length {}"),
    ("minItems", "min items {}"),
    ("maxItems", "max items {}"),
    ("pattern", "pattern `{}`"),
    ("format", "format {}"),
)


def _schema_notes(name: str, schema: Mapping[str, object], required: set[str]) -> str:
    notes = ["required"] if name in required else []
    for key, template in _CONSTRAINT_KEYS:
        if key in schema:
            notes.append(template.format(schema[key]))
    if "anyOf" in schema:
        options = typing.cast(list[Mapping[str, object]], schema["anyOf"])
        for option in options:
            if option.get("type") == "null":
                continue
            for key, template in _CONSTRAINT_KEYS:
                if key in option:
                    notes.append(template.format(option[key]))
    if "description" in schema:
        notes.append(str(schema["description"]))
    return "; ".join(notes)


def _schema_default(schema: Mapping[str, object]) -> str:
    if schema.get("default") is None:
        return ""
    return _json_code(schema["default"])


def _property_rows(
    properties: Mapping[str, Mapping[str, object]], required: set[str]
) -> list[list[str]]:
    return [
        [
            _code(name),
            _schema_type(schema),
            _schema_default(schema),
            _schema_notes(name, schema, required),
        ]
        for name, schema in properties.items()
    ]


def _variant_sections(
    param_name: str, variants: list[Mapping[str, object]]
) -> list[str]:
    """A ``Variants of `param_name`` block: one field table per discriminated variant."""
    lines = [f"#### Variants of {_code(param_name)}", ""]
    for index, variant in enumerate(variants):
        lines += [f"##### {_code(_oneof_variant_name(variant, index))}", ""]
        description = variant.get("description")
        if description:
            lines += [_escape_angles(str(description).strip()), ""]
        properties = typing.cast(
            Mapping[str, Mapping[str, object]], variant.get("properties", {})
        )
        required = set(typing.cast(list[str], variant.get("required", [])))
        if properties:
            lines += _table(
                ["Field", "Type", "Default", "Notes"],
                _property_rows(properties, required),
            )
        lines.append("")
    return lines[:-1]


def _access(annotations: Mapping[str, object]) -> str:
    parts = ["read-only" if annotations.get("readOnlyHint") else "write"]
    if annotations.get("destructiveHint"):
        parts.append("destructive")
    parts.append(
        "idempotent" if annotations.get("idempotentHint") else "not idempotent"
    )
    if annotations.get("openWorldHint"):
        parts.append("open world")
    return ", ".join(parts)


def render_mcp_tools(
    surface: Mapping[str, object], sensitivities: Mapping[str, str]
) -> str:
    """Render the MCP tool reference from the client-visible surface and runtime tiers."""
    tools = sorted(
        typing.cast(list[Mapping[str, object]], surface["tools"]),
        key=lambda tool: str(tool["name"]),
    )
    missing = [
        str(tool["name"]) for tool in tools if str(tool["name"]) not in sensitivities
    ]
    if missing:
        raise ValueError(f"no registered sensitivity for listed tools: {missing}")
    count = int(typing.cast(int, surface["tool_count"]))
    lines = [
        _marker(
            "the tool list the MCP server hands a connecting client, plus the "
            "registered tool metadata"
        ),
        "# MCP tool reference",
        "",
        f"The standard registry exposes {count} tools. Each entry below is the "
        "tool's client-visible definition — its description, parameters, and "
        "MCP annotations — plus the maximum sensitivity the server derives from "
        "its typed response. Every tool returns the response envelope described "
        "in [`architecture.md`](../architecture.md): `status`, `summary`, "
        "`data`, `actions`, with `error` on failure and `next_cursor` when more "
        "rows remain. How the server is installed and driven: "
        "[MCP server](../guides/mcp-server.md).",
        "",
        "## Tools",
        "",
    ]
    summary_rows = []
    for tool in tools:
        name = str(tool["name"])
        definition = typing.cast(Mapping[str, object], tool["definition"])
        annotations = typing.cast(
            Mapping[str, object], definition.get("annotations", {})
        )
        summary_rows.append([
            f"[{_code(name)}](#{_slug(name)})",
            first_sentence(str(definition.get("description", "")).strip()),
            _access(annotations),
            _code(sensitivities[name]),
        ])
    lines += _table(["Tool", "Purpose", "Access", "Max sensitivity"], summary_rows)
    lines.append("")
    for tool in tools:
        name = str(tool["name"])
        definition = typing.cast(Mapping[str, object], tool["definition"])
        annotations = typing.cast(
            Mapping[str, object], definition.get("annotations", {})
        )
        schema = typing.cast(Mapping[str, object], definition.get("inputSchema", {}))
        properties = typing.cast(
            Mapping[str, Mapping[str, object]], schema.get("properties", {})
        )
        required = set(typing.cast(list[str], schema.get("required", [])))
        lines += [f"### {name}", ""]
        lines += [_escape_angles(str(definition.get("description", "")).strip()), ""]
        lines += [
            f"Access: {_access(annotations)}. Maximum sensitivity: "
            f"{_code(sensitivities[name])}.",
            "",
        ]
        if properties:
            lines += _table(
                ["Parameter", "Type", "Default", "Notes"],
                _property_rows(properties, required),
            )
            for prop_name, prop_schema in properties.items():
                variants = _oneof_variants(prop_schema)
                if variants:
                    lines.append("")
                    lines += _variant_sections(prop_name, variants)
        else:
            lines.append("No parameters.")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def live_mcp_surface() -> tuple[dict[str, object], dict[str, str]]:
    """The tool list a connecting client receives, and each tool's maximum sensitivity.

    One in-process boot of the standard registry serves both: the client list
    is what ``moneybin mcp serve`` would hand a client (the same inventory
    ``tests/fixtures/mcp_surface/standard.json`` freezes), and the tiers come
    from the registered functions behind it. No database is opened.
    """
    from fastmcp import Client

    from moneybin.mcp.server import mcp, register_core_tools
    from moneybin.mcp.surface_inventory import SurfaceInventory

    register_core_tools()

    async def inventory() -> dict[str, object]:
        async with Client(mcp) as client:
            return SurfaceInventory.from_tools(await client.list_tools()).to_dict()

    surface = asyncio.run(inventory())
    sensitivities: dict[str, str] = {}
    for tool in asyncio.run(mcp.list_tools(run_middleware=False)):
        fn = getattr(tool, "fn", None)
        sensitivity = getattr(fn, "_mcp_maximum_sensitivity", None)
        if sensitivity is None:
            raise ValueError(f"tool {tool.name} carries no _mcp_maximum_sensitivity")
        sensitivities[tool.name] = str(getattr(sensitivity, "value", sensitivity))
    return surface, sensitivities


