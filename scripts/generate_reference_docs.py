def generated_pages() -> dict[Path, str]:
    """Every generated page, keyed by path relative to ``docs/reference/``."""
    from typer.main import get_command

    from moneybin.cli.main import app
    from moneybin.config import MoneyBinSettings

    root = get_command(app)
    if not isinstance(root, click.Group):
        raise TypeError("the moneybin root command is not a click.Group")
    pages = {Path("cli") / name: text for name, text in render_cli_pages(root).items()}
    pages[Path("mcp-tools.md")] = render_mcp_tools(*live_mcp_surface())
    pages[Path("configuration.md")] = render_configuration(MoneyBinSettings)
    return pages


def _orphaned_cli_pages(reference_dir: Path, pages: Mapping[Path, str]) -> list[Path]:
    """Generated CLI pages on disk whose command the tree no longer renders."""
    cli_dir = reference_dir / "cli"
    marker = _marker("the Typer command tree")
    return [
        existing.relative_to(reference_dir)
        for existing in (sorted(cli_dir.glob("*.md")) if cli_dir.exists() else [])
        if existing.relative_to(reference_dir) not in pages
        and existing.read_text().startswith(marker)
    ]


def stale_pages(reference_dir: Path = _REFERENCE_DIR) -> list[Path]:
    """Generated paths whose checked-in text differs, is missing, or is orphaned."""
    pages = generated_pages()
    stale = [
        path
        for path, text in pages.items()
        if not (reference_dir / path).exists()
        or (reference_dir / path).read_text() != text
    ]
    return stale + _orphaned_cli_pages(reference_dir, pages)


def write_pages(reference_dir: Path = _REFERENCE_DIR) -> list[Path]:
    """Write every page; drop generated CLI pages whose command no longer exists."""
    pages = generated_pages()
    written: list[Path] = []
    for path, text in pages.items():
        target = reference_dir / path
        target.parent.mkdir(parents=True, exist_ok=True)
        if not target.exists() or target.read_text() != text:
            target.write_text(text)
            written.append(path)
    for orphan in _orphaned_cli_pages(reference_dir, pages):
        (reference_dir / orphan).unlink()
        written.append(orphan)
    return written


def main(argv: list[str] | None = None) -> int:
    """Write the pages, or with ``--check`` report which ones are stale."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--reference-dir", type=Path, default=_REFERENCE_DIR)
    args = parser.parse_args(argv)
    reference_dir: Path = args.reference_dir
    if reference_dir.resolve().is_relative_to(_REPO_ROOT):
        reference_dir = reference_dir.resolve().relative_to(_REPO_ROOT)
    if args.check:
        stale = stale_pages(args.reference_dir)
        for path in stale:
            print(f"stale: {reference_dir / path}")  # noqa: T201  # script output
        return 1 if stale else 0
    for path in write_pages(args.reference_dir):
        print(f"wrote {reference_dir / path}")  # noqa: T201  # script output
    return 0


if __name__ == "__main__":
    sys.exit(main())
