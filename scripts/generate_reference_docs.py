def _plain(text: str) -> str:
    r"""Help text as ``--help`` shows it: the docstring cleaned, rich markup rendered.

    Typer's ``rich`` mode does the same, and rich drops click's ``\b`` marker
    with the other control codes.
    """
    return Text.from_markup(inspect.cleandoc(text)).plain


def _help_prose(text: str | None) -> str:
    """Return option or argument help as one paragraph."""
    return _escape_angles(_plain(text).strip()) if text else ""


_LIST_ITEM = re.compile(r"^\s*(?:[-*+]|\d+[.)])\s")
_CONSOLE_LINE = re.compile(r"^(?:#|.*(?<![\w./:@-])moneybin\s)")
_CONTINUATION = re.compile(r"\\\n\s*")


def _fence(lines: list[str]) -> tuple[str, str]:
    """A verbatim block as ``(language, body)``; ``console`` when it is a transcript."""
    body = textwrap.dedent("\n".join(lines)).strip("\n")
    commands = _CONTINUATION.sub(" ", body).splitlines()
    shell = all(_CONSOLE_LINE.match(line) for line in commands if line.strip())
    return ("console" if shell else "text"), body


def _help_blocks(text: str | None) -> str:
    """Return a command's help as Markdown, keeping its verbatim blocks verbatim.

    Typer joins the first paragraph's lines and prints every later paragraph
    line by line, so an indented example or option table survives ``--help``
    but not Markdown, which fuses indented lines into the paragraph above. Such
    a paragraph keeps its non-indented lead as prose and renders the rest as a
    fenced block; indented list items stay prose, which Markdown renders as a
    list. A transcript fence is ``console``, so the docs guard checks it as it
    does every other fenced invocation.
    """
    if not text:
        return ""
    first, *rest = re.split(r"\n\s*\n", _plain(text).strip())
    blocks: list[str | tuple[str, str]] = [_escape_angles(first.replace("\n", " "))]
    for paragraph in rest:
        lines = paragraph.split("\n")
        split = next(
            (
                index
                for index, line in enumerate(lines)
                if line[:1].isspace() and not _LIST_ITEM.match(line)
            ),
            len(lines),
        )
        if split:
            blocks.append(_escape_angles("\n".join(lines[:split])))
        if split < len(lines):
            language, body = _fence(lines[split:])
            previous = blocks[-1]
            if isinstance(previous, tuple) and previous[0] == language:
                blocks[-1] = (language, previous[1] + "\n\n" + body)
            else:
                blocks.append((language, body))
    return "\n\n".join(
        block if isinstance(block, str) else f"```{block[0]}\n{block[1]}\n```"
        for block in blocks
    )


def _option_names(option: click.Option) -> str:
    names = ", ".join(option.opts)
    if option.secondary_opts:
        names += " / " + ", ".join(option.secondary_opts)
    return names


def _param_type(param: click.Parameter) -> str:
    kind = param.type
    if isinstance(param, click.Option) and param.is_flag:
        return "flag"
    if isinstance(param, click.Option) and param.count:
        return "count"
    if isinstance(kind, click.Choice):
        rendered = "one of " + ", ".join(_code(choice) for choice in kind.choices)
    elif isinstance(kind, (click.IntRange, click.FloatRange)):
        base = "int" if isinstance(kind, click.IntRange) else "float"
        bounds = []
        if kind.min is not None:
            bounds.append(f"≥ {kind.min}")
        if kind.max is not None:
            bounds.append(f"≤ {kind.max}")
        rendered = base + (f" ({', '.join(bounds)})" if bounds else "")
    else:
        rendered = {
            "text": "text",
            "integer": "int",
            "float": "float",
            "boolean": "bool",
            "path": "path",
            "file": "file",
            "datetime": "datetime",
            "uuid": "uuid",
        }.get(kind.name, kind.name)
    if param.nargs not in (1, None) or getattr(param, "multiple", False):
        rendered += ", repeatable"
    return rendered


_CLICK_UNSET = getattr(click.core, "UNSET", None)  # click 8.3's "no default" sentinel


def _render_default(value: object) -> str:
    if value is None or value is PydanticUndefined or value is _CLICK_UNSET:
        return ""
    if isinstance(value, enum.Enum):
        value = value.value
    if isinstance(value, bool):
        return _code(str(value).lower())
    if isinstance(value, (list, tuple)):
        return ", ".join(_render_default(item) for item in value) if value else ""
    if isinstance(value, Path):
        return _code(value)
    if isinstance(value, str):
        return _code(value) if value else '`""`'
    return _code(value)


def _option_default(option: click.Option, ctx: click.Context) -> str:
    bare_flag = option.is_flag and not option.secondary_opts
    if bare_flag or option.show_default is False:
        return ""
    if isinstance(option.show_default, str):
        return option.show_default
    return _render_default(option.get_default(ctx, call=True))


def _option_description(option: click.Option) -> str:
    """The option's help, prefixed when required and suffixed with its env var."""
    parts = ["Required." if option.required else "", _help_prose(option.help)]
    envvar = option.envvar
    if envvar:
        names = [envvar] if isinstance(envvar, str) else list(envvar)
        parts.append("Env: " + ", ".join(_code(name) for name in names) + ".")
    return " ".join(part for part in parts if part)


def _option_rows(
    options: Iterable[click.Option], ctx: click.Context
) -> list[list[str]]:
    return [
        [
            _code(_option_names(option)),
            _param_type(option),
            _option_default(option, ctx),
            _option_description(option),
        ]
        for option in options
    ]


def _walk(
    command: click.Command, ctx: click.Context
) -> list[tuple[click.Command, click.Context]]:
    """Depth-first (command, context) pairs below ``command``, skipping hidden ones."""
    found: list[tuple[click.Command, click.Context]] = []
    if not isinstance(command, click.Group):
        return found
    for name in command.list_commands(ctx):
        child = command.get_command(ctx, name)
        if child is None or child.hidden:
            continue
        child_ctx = click.Context(child, info_name=name, parent=ctx)
        found.append((child, child_ctx))
        found.extend(_walk(child, child_ctx))
    return found


def _command_section(
    command: click.Command, ctx: click.Context, level: int = 2, intro: str = ""
) -> list[str]:
    path = ctx.command_path
    lines = [f"{'#' * level} {path}", ""]
    if command.deprecated:
        lines += ["**Deprecated.**", ""]
    help_text = _help_blocks(command.help)
    if help_text:
        lines += [help_text, ""]
    if intro:
        lines += [intro, ""]
    # A synopsis names the command's shape; it is not a transcript, so it is
    # an inline span (the docs guard holds fenced blocks to "runs as written").
    usage = " ".join([path, *command.collect_usage_pieces(ctx)])
    lines += [f"Usage: `{usage}`", ""]
    if isinstance(command, click.Group):
        rows = []
        for name in command.list_commands(ctx):
            child = command.get_command(ctx, name)
            if child is None or child.hidden:
                continue
            child_path = f"{path} {name}"
            rows.append([
                f"[{_code(child_path)}](#{_slug(child_path)})",
                child.get_short_help_str(limit=200),
            ])
        if rows:
            lines += ["**Commands**", ""]
            lines += _table(["Command", "Purpose"], rows)
            lines.append("")
    # Typer arguments carry ``hidden``; plain click arguments do not.
    arguments = [
        p
        for p in command.params
        if isinstance(p, click.Argument) and not getattr(p, "hidden", False)
    ]
    if arguments:
        rows = [
            [
                _code(argument.make_metavar(ctx)),
                _param_type(argument),
                "yes" if argument.required else "no",
                _help_prose(getattr(argument, "help", None)),
            ]
            for argument in arguments
        ]
        lines += ["**Arguments**", ""]
        lines += _table(["Argument", "Type", "Required", "Description"], rows)
        lines.append("")
    options = [
        p for p in command.params if isinstance(p, click.Option) and not p.hidden
    ]
    if options:
        lines += ["**Options**", ""]
        lines += _table(
            ["Option", "Type", "Default", "Description"], _option_rows(options, ctx)
        )
        lines.append("")
    return lines


_PAGE_INTRO = (
    "Generated from the registered command tree, so every option below is one "
    "the command declares; `--help` on any command prints the same text. "
    "Shared flags, exit codes, and JSON envelopes: "
    "[CLI reference](../../guides/cli-reference.md)."
)


def render_cli_pages(root: click.Group) -> dict[str, str]:
    """Return ``{relative path: text}`` for the CLI reference directory."""
    root_ctx = click.Context(root, info_name="moneybin")
    pages: dict[str, str] = {}
    index_rows: list[list[str]] = []
    for name in root.list_commands(root_ctx):
        command = root.get_command(root_ctx, name)
        if command is None or command.hidden:
            continue
        ctx = click.Context(command, info_name=name, parent=root_ctx)
        summary = command.get_short_help_str(limit=200)
        index_rows.append([f"[{_code('moneybin ' + name)}]({name}.md)", summary])
        lines = [_marker("the Typer command tree")]
        lines += _command_section(command, ctx, level=1, intro=_PAGE_INTRO)
        for child, child_ctx in _walk(command, ctx):
            lines += _command_section(child, child_ctx)
        pages[f"{name}.md"] = "\n".join(lines).rstrip() + "\n"

    root_options = [
        p for p in root.params if isinstance(p, click.Option) and not p.hidden
    ]
    index = [
        _marker("the Typer command tree"),
        "# CLI command tree",
        "",
        "One page per top-level command, generated from the registered command "
        "tree. Hidden commands are omitted, as they are from `--help`. For the "
        "conventions every command shares (standard flags, exit codes, output "
        "envelopes, date formats) read the hand-written "
        "[CLI reference](../../guides/cli-reference.md).",
        "",
        "Usage: `" + " ".join(["moneybin", *root.collect_usage_pieces(root_ctx)]) + "`",
        "",
        "**Global options**",
        "",
        *_table(
            ["Option", "Type", "Default", "Description"],
            _option_rows(root_options, root_ctx),
        ),
        "",
        "**Commands**",
        "",
        *_table(["Command", "Purpose"], index_rows),
    ]
    pages["README.md"] = "\n".join(index).rstrip() + "\n"
    return pages


