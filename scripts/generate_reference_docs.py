_MARKER = (
    "<!-- Generated by {script} from {source}. Do not edit; "
    "run `make generate-docs` after changing the source. -->"
)


def _marker(source: str) -> str:
    return _MARKER.format(script=_SCRIPT, source=source)


_CODE_SPAN_OR_ANGLE = re.compile(r"(`[^`]*`|\\<)|<")


def _escape_angles(text: str) -> str:
    """Escape ``<`` outside code spans: a bare ``<placeholder>`` is HTML to GitHub."""
    return _CODE_SPAN_OR_ANGLE.sub(lambda m: m.group(1) or "\\<", text)


def _cell(text: object) -> str:
    """Escape a table cell: pipes break the row, newlines break the table."""
    return _escape_angles(str(text).replace("|", "\\|").replace("\n", " ").strip())


def _code(text: object) -> str:
    return f"`{text}`"


def _table(headers: list[str], rows: Iterable[list[str]]) -> list[str]:
    lines = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    lines.extend("| " + " | ".join(_cell(cell) for cell in row) + " |" for row in rows)
    return lines


def _slug(heading: str) -> str:
    """GitHub's heading anchor: lower-case, spaces to hyphens, punctuation dropped."""
    text = re.sub(r"[^\w\- ]", "", heading.lower())
    return text.replace(" ", "-")


