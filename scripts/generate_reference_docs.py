def _submodel(annotation: object) -> type[BaseModel] | None:
    if isinstance(annotation, type) and issubclass(annotation, BaseModel):
        return annotation
    origin = typing.get_origin(annotation)
    if origin is typing.Union or origin is types.UnionType:
        for arg in typing.get_args(annotation):
            if isinstance(arg, type) and issubclass(arg, BaseModel):
                return arg
    return None


def _annotation_text(annotation: object) -> str:
    origin = typing.get_origin(annotation)
    args = typing.get_args(annotation)
    if annotation is SecretStr:
        return "secret"
    if origin is typing.Literal:
        return "one of " + ", ".join(_json_code(arg) for arg in args)
    if origin is typing.Union or origin is types.UnionType:
        parts = [_annotation_text(arg) for arg in args if arg is not type(None)]
        optional = any(arg is type(None) for arg in args)
        return " or ".join(parts) + (" (optional)" if optional else "")
    if origin in (list, tuple, set, frozenset):
        inner = ", ".join(_annotation_text(arg) for arg in args if arg is not Ellipsis)
        return f"list of {inner}" if inner else "list"
    if origin is dict:
        key, value = (_annotation_text(arg) for arg in args) if args else ("any", "any")
        return f"mapping of {key} to {value}"
    if isinstance(annotation, type):
        if issubclass(annotation, enum.Enum):
            return "one of " + ", ".join(_code(member.value) for member in annotation)
        return {"str": "text", "int": "int", "float": "float", "bool": "bool"}.get(
            annotation.__name__, annotation.__name__
        )
    return str(annotation)


def _constraints(metadata: Iterable[object]) -> list[str]:
    notes: list[str] = []
    for item in metadata:
        for attribute, template in (
            ("ge", "≥ {}"),
            ("gt", "> {}"),
            ("le", "≤ {}"),
            ("lt", "< {}"),
            ("min_length", "min length {}"),
            ("max_length", "max length {}"),
        ):
            value = getattr(item, attribute, None)
            if value is not None:
                notes.append(template.format(value))
    return notes


def _settings_default(field: typing.Any, env: str) -> str:
    if env in _PROFILE_DERIVED_DEFAULTS:
        return _PROFILE_DERIVED_DEFAULTS[env]
    if field.default_factory is not None:
        value = field.default_factory()
    else:
        value = field.default
    if value is PydanticUndefined:
        return "required"
    if isinstance(value, SecretStr):
        return "built in" if value.get_secret_value() else "unset"
    if isinstance(value, Path):
        home = Path.home()
        try:
            value = Path("~") / value.relative_to(home)
        except ValueError:
            pass
        return _code(value)
    if value is None:
        return "unset"
    if isinstance(value, dict):
        return _code(json.dumps(value, sort_keys=True))
    return _render_default(value)


_PROFILE_DERIVED_DEFAULTS = {
    "MONEYBIN_DATABASE__PATH": "`<profile dir>/moneybin.duckdb`",
    "MONEYBIN_DATABASE__BACKUP_PATH": "`<profile dir>/backups`",
    "MONEYBIN_DATABASE__TEMP_DIRECTORY": "`<profile dir>/temp`",
    "MONEYBIN_DATA__RAW_DATA_PATH": "`<profile dir>/raw`",
    "MONEYBIN_DATA__TEMP_DATA_PATH": "`<profile dir>/temp`",
    "MONEYBIN_LOGGING__LOG_FILE_PATH": "`<profile dir>/logs/moneybin.log`",
}


def _field_row(
    model: type[BaseModel], prefix: list[str], name: str, field: typing.Any
) -> list[str]:
    # pydantic-settings resolves nested env names from field names, not
    # aliases: the `import_` section reads MONEYBIN_IMPORT___* (three
    # underscores), which `MoneyBinSettings.import_` documents.
    env = "MONEYBIN_" + "__".join(part.upper() for part in [*prefix, name])
    if not field.description:
        raise ValueError(f"{model.__name__}.{name} ({env}) has no description")
    notes = _constraints(field.metadata)
    type_text = _annotation_text(field.annotation)
    if notes:
        type_text += " (" + ", ".join(notes) + ")"
    return [_code(env), type_text, _settings_default(field, env), field.description]


def _settings_rows(model: type[BaseModel], prefix: list[str]) -> list[list[str]]:
    rows: list[list[str]] = []
    for name, field in model.model_fields.items():
        sub = _submodel(field.annotation)
        if sub is not None:
            rows.extend(_settings_rows(sub, [*prefix, name]))
        else:
            rows.append(_field_row(model, prefix, name, field))
    return rows


#: Sections `MoneyBinSettings.__init__` passes whole from the active profile.
#: A constructor value is the highest-precedence source, so nothing in these
#: sections can be set from the environment or the dotenv file.
_PROFILE_BOUND_SECTIONS = {"database", "data", "logging"}
_PROFILE_BOUND_NOTE = (
    "`MoneyBinSettings` builds this whole section from the active profile's "
    "directory when it is constructed, and a constructor value outranks the "
    "environment and the dotenv file, so the variables below are not read "
    "today: every profile runs on the defaults shown."
)


def render_configuration(settings_cls: type[BaseSettings]) -> str:
    """Render the configuration reference from the settings model."""
    config = settings_cls.model_config
    prefix = str(config.get("env_prefix", ""))
    delimiter = str(config.get("env_nested_delimiter", "__"))
    lines = [
        _marker("`MoneyBinSettings` in `src/moneybin/config.py`"),
        "# Configuration reference",
        "",
        "Every setting MoneyBin reads, one row per value. Set a value as an "
        f"environment variable with the `{prefix}` prefix, joining nested "
        f"sections with `{delimiter}` (`{prefix}MCP{delimiter}MAX_ROWS`), or "
        "put the same lines in `.env.<profile>` under the data home, falling "
        "back to `.env`. Precedence is explicit constructor values, then the "
        "process environment, then the dotenv file. `MONEYBIN_HOME` itself "
        "must come from the environment or `--home`: the dotenv file lives "
        "inside the home it would name.",
        "",
        "Paths marked `<profile dir>` resolve to `<home>/profiles/<profile>/`.",
        "",
    ]
    sections: list[tuple[str, str, type[BaseModel], str]] = []
    for name, field in settings_cls.model_fields.items():
        sub = _submodel(field.annotation)
        if sub is not None:
            summary = field.description or (sub.__doc__ or "").strip().split("\n")[0]
            sections.append((field.alias or name, name, sub, summary))
    top_rows = [
        _field_row(settings_cls, [], name, field)
        for name, field in settings_cls.model_fields.items()
        if _submodel(field.annotation) is None
    ]
    if top_rows:
        lines += ["## Top level", ""]
        lines += _table(["Variable", "Type", "Default", "Description"], top_rows)
        lines.append("")
    for key, field_name, model, description in sections:
        lines += [f"## {key}", ""]
        if description:
            lines += [description, ""]
        if field_name in _PROFILE_BOUND_SECTIONS:
            lines += [_PROFILE_BOUND_NOTE, ""]
        lines += _table(
            ["Variable", "Type", "Default", "Description"],
            _settings_rows(model, [field_name]),
        )
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


