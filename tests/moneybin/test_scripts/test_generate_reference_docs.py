def test_cli_pages_are_one_per_top_level_command_plus_an_index() -> None:
    pages = render_cli_pages(toy)
    assert set(pages) == {"README.md", "db.md", "preview.md", "stats.md"}
    assert pages["README.md"].startswith("<!-- Generated by")
    assert "[`moneybin db`](db.md)" in pages["README.md"]
    assert (
        "| `--home` | path |  | Data directory. Env: `TOY_HOME`. |"
        in pages["README.md"]
    )


def test_cli_page_renders_click_usage_arguments_and_options() -> None:
    page = render_cli_pages(toy)["db.md"]
    assert "# moneybin db" in page
    assert "## moneybin db restore" in page
    assert "Usage: `moneybin db restore [OPTIONS] BACKUP_PATH`" in page
    assert "| `BACKUP_PATH` | text | yes |  |" in page
    assert "| `--passphrase` | flag |  | Derive the key from a passphrase. |" in page
    assert (
        "| `-o, --output` | one of `text`, `json` | `text` | Output format. |" in page
    )
    assert "Longer help paragraph." in page


