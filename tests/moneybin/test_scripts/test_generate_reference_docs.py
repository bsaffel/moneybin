def test_cli_page_renders_boolean_pair_defaults_and_escapes_placeholders() -> None:
    """`<scope>` outside a code span is HTML to GitHub; a bool pair has a default."""
    page = render_cli_pages(toy)["stats.md"]
    assert "Show stats for \\<scope>." in page
    assert (
        "| `--refresh / --no-refresh` | flag | `true` | "
        "Refresh \\<scope> first; see `moneybin refresh <step>`. |"
    ) in page


def test_cli_page_fences_indented_help_blocks_and_keeps_lists_as_prose() -> None:
    """`--help` joins the first paragraph and prints later indented lines as is.

    An option table becomes a `text` fence, a transcript a `console` fence
    (consecutive ones merge, and a backslash continuation still counts as a
    transcript line), and an indented list stays prose. Nothing inside a fence
    is escaped.
    """
    page = render_cli_pages(toy)["preview.md"]
    assert (
        "Preview a file before importing it.\n\n"
        "Pass exactly one of:\n\n"
        "```text\n--sheet <name>   read one sheet\n--all            read every sheet\n```\n\n"
        "Supported types:\n  - CSV\n  - Excel\n\n"
        "Examples:\n\n"
        "```console\nmoneybin preview <path>\n\n# With a sheet\n"
        "moneybin preview a.xlsx --sheet Sheet1\n```\n\n"
        "Or piped:\n\n"
        "```console\ncat list.txt \\\n  | moneybin preview -\n```\n\n"
        "Generated from the registered command tree"
    ) in page


def test_stale_pages_reports_orphaned_generated_cli_pages(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """A generated page whose command is gone is stale, and write_pages drops it."""
    import scripts.generate_reference_docs as generator

    monkeypatch.setattr(
        generator, "generated_pages", lambda: {Path("cli") / "db.md": "# db\n"}
    )
    cli_dir = tmp_path / "cli"
    cli_dir.mkdir()
    (cli_dir / "db.md").write_text("# db\n")
    (cli_dir / "gone.md").write_text(
        "<!-- Generated by scripts/generate_reference_docs.py from the Typer "
        "command tree. Do not edit; run `make generate-docs` after changing the "
        "source. -->\n"
    )
    (cli_dir / "hand-written.md").write_text("# Kept\n")
    assert stale_pages(tmp_path) == [Path("cli") / "gone.md"]
    assert write_pages(tmp_path) == [Path("cli") / "gone.md"]
    assert sorted(p.name for p in cli_dir.iterdir()) == ["db.md", "hand-written.md"]


SURFACE: dict[str, Any] = {
    "tool_count": 2,
    "tools": [
        {
            "name": "zeta",
            "definition": {
                "description": "Second sentence first. Then more.",
                "annotations": {"readOnlyHint": False, "destructiveHint": True},
                "inputSchema": {"properties": {}, "type": "object"},
            },
        },
        {
            "name": "accounts",
            "definition": {
                "description": "List accounts.",
                "annotations": {"readOnlyHint": True, "idempotentHint": True},
                "inputSchema": {
                    "properties": {
                        "limit": {"type": "integer", "default": 100, "minimum": 1},
                        "view": {
                            "type": "string",
                            "enum": ["list", "detail"],
                            "default": "list",
                        },
                        "query": {
                            "anyOf": [{"type": "string"}, {"type": "null"}],
                            "default": None,
                        },
                    },
                    "required": ["view"],
                    "type": "object",
                },
            },
        },
    ],
}


def test_mcp_page_sorts_tools_and_renders_schema_rows() -> None:
    page = render_mcp_tools(SURFACE, {"accounts": "critical", "zeta": "low"})
    assert page.index("### accounts") < page.index("### zeta")
    assert "The standard registry exposes 2 tools." in page
    assert (
        "| [`zeta`](#zeta) | Second sentence first. | write, destructive, not idempotent | `low` |"
        in page
    )
    assert "| `limit` | integer | `100` | ≥ 1 |" in page
    assert "| `view` | one of `list`, `detail` | `list` | required |" in page
    assert "| `query` | string |  |  |" in page
    assert "No parameters." in page


def test_mcp_page_refuses_a_tool_without_a_registered_sensitivity() -> None:
    with pytest.raises(ValueError, match="zeta"):
        render_mcp_tools(SURFACE, {"accounts": "critical"})


def test_live_mcp_surface_lists_every_tool_with_a_registered_tier() -> None:
    """One in-process boot, no database: what a client sees, plus each tier.

    The page renders from this rather than from the frozen snapshot, so a tool
    description edited without regenerating fails the unit drift test instead
    of only the integration snapshot check.
    """
    surface, sensitivities = live_mcp_surface()
    tools = cast(list[dict[str, object]], surface["tools"])
    assert tools
    assert surface["tool_count"] == len(tools)
    assert {str(tool["name"]) for tool in tools} <= set(sensitivities)


class Nested(BaseModel):
    """A nested settings section."""

    limit: int = Field(default=10, ge=1, description="Row cap.")
    token: SecretStr | None = Field(default=None, description="API token.")


class ToySettings(BaseSettings):
    """A settings root with a scalar, an aliased section, and a home-relative path."""

    model_config = SettingsConfigDict(env_prefix="MONEYBIN_", env_nested_delimiter="__")

    debug: bool = Field(default=False, description="Enable debug mode.")
    import_: Nested = Field(default_factory=Nested, alias="import")
    inbox: Path = Field(
        default_factory=lambda: Path.home() / "Documents", description="Inbox root."
    )
    logging: Nested = Field(default_factory=Nested, description="Log settings.")


def test_configuration_page_marks_the_sections_the_profile_passes_whole() -> None:
    """`database`, `data`, and `logging` come from the profile, not the environment."""
    page = render_configuration(ToySettings)
    note = "so the variables below are not read today"
    assert page.count(note) == 1
    assert page.index("## logging") < page.index(note)
    assert "profile set" not in page


def test_configuration_page_derives_env_names_from_field_names() -> None:
    page = render_configuration(ToySettings)
    assert "| `MONEYBIN_DEBUG` | bool | `false` | Enable debug mode. |" in page
    assert "## import" in page
    assert "| `MONEYBIN_IMPORT___LIMIT` | int (≥ 1) | `10` | Row cap. |" in page
    assert (
        "| `MONEYBIN_IMPORT___TOKEN` | secret (optional) | unset | API token. |" in page
    )


def test_configuration_page_relativizes_home_and_never_prints_secrets() -> None:
    page = render_configuration(ToySettings)
    assert "| `MONEYBIN_INBOX` | Path | `~/Documents` | Inbox root. |" in page
    assert str(Path.home()) not in page


def test_configuration_page_refuses_an_undescribed_field() -> None:
    class Bare(BaseSettings):
        model_config = SettingsConfigDict(env_prefix="MONEYBIN_")
        debug: bool = False

    with pytest.raises(ValueError, match="MONEYBIN_DEBUG"):
        render_configuration(Bare)
