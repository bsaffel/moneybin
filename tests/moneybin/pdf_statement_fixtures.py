def write_scanned_statement_pdf(tmp_path: Path) -> Path:
    """A PDF with no text layer, as a scanned statement presents."""
    dest = tmp_path / "scanned_statement.pdf"
    dest.write_bytes(_minimal_pdf(()))
    return dest


